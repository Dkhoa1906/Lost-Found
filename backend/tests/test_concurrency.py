"""Race checks through HTTP and the public expiration command, on real connections."""

from concurrent.futures import ThreadPoolExecutor
from threading import Barrier

import psycopg
import pytest
from conftest import AUTHOR, CLAIMANT, headers

from app.db import get_conn
from app.main import app


@pytest.mark.parametrize("attempt", range(4))
@pytest.mark.parametrize("operation", ["archive", "expire"])
def test_handover_and_post_closure_have_consistent_lock_order(
    client, conversation, db, database_uri, operation, attempt
):
    pid, cid = conversation["post_id"], conversation["claim_id"]
    assert (
        client.post(f"/claims/{cid}/confirm", headers=headers(AUTHOR)).status_code
        == 200
    )
    if operation == "expire":
        db.execute(
            "update public.posts set expires_at=now()-interval '1 second' where id=%s",
            (pid,),
        )
    db.commit()

    def connection():
        with psycopg.connect(database_uri) as conn:
            yield conn

    original = app.dependency_overrides[get_conn]
    app.dependency_overrides[get_conn] = connection
    barrier = Barrier(2)

    def confirm():
        barrier.wait(timeout=5)
        return client.post(
            f"/claims/{cid}/confirm", headers=headers(CLAIMANT)
        ).status_code

    def close():
        barrier.wait(timeout=5)
        if operation == "archive":
            return client.patch(
                f"/posts/{pid}/status",
                headers=headers(AUTHOR),
                json={"status": "ARCHIVED"},
            ).status_code
        with psycopg.connect(database_uri) as conn:
            return conn.execute("select public.expire_posts()").fetchone()[0]

    try:
        with ThreadPoolExecutor(max_workers=2) as pool:
            a, b = pool.submit(confirm), pool.submit(close)
            confirmed, closed = a.result(timeout=15), b.result(timeout=15)
        assert confirmed in (200, 409)
        if operation == "archive":
            assert sorted([confirmed, closed]) == [200, 409]
        else:
            assert closed in (0, 1)
        posts = client.get("/admin/posts", headers=headers()).json()["items"]
        assert next(p["status"] for p in posts if p["id"] == pid) in (
            "RESOLVED",
            "ARCHIVED",
            "EXPIRED",
        )
    finally:
        app.dependency_overrides[get_conn] = original
        # This URI is generated by the owned embedded test cluster, never .env.
        db.rollback()
        db.execute("truncate auth.users cascade")
        db.commit()
